function statusTone(
  status: "good" | "fair" | "poor" | "unknown",
): "positive" | "warning" | "negative" | "info" {
  if (status === "good") return "positive";
  if (status === "fair") return "warning";
  if (status === "poor") return "negative";
  return "info";
}

